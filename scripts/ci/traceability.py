#!/usr/bin/env python3
"""Traceability matrix URS -> test -> result (docs/ci/README.md stage C7, ADR 0015, URS-VAL-001).

Reads
  - the requirement index      docs/validation/urs-index.csv  (ID, risk, release; generated by urs_index.py)
  - @Requirement annotations   in the Java test sources (class level = every test in the class)
  - JUnit XML results          surefire-reports/ and failsafe-reports/ (TEST-*.xml)
  - requirement text           docs/product/URS.md, only if present (local runs; it is not in Git)
Writes traceability.md (job summary) and traceability.html (self-contained evidence page) to --out.

Fails (exit 1) when
  - a test references a requirement ID that is not in the index (typo or withdrawn ID),
  - a test linked to a requirement failed or errored,
  - with --require-mvp: an active MVP requirement has no passing test (the release gate; off until MVP).
"""
import argparse
import csv
import datetime as dt
import glob
import html
import os
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict

ANNOTATION = re.compile(r"@Requirement\s*\(\s*(\{[^}]*\}|\"[^\"]*\")\s*\)")
IDS = re.compile(r"URS-[A-Z]+-\d{3}")
DECL = re.compile(r"\b(?:class|record|interface)\s+(\w+)|\bvoid\s+(\w+)\s*\(")
PACKAGE = re.compile(r"^\s*package\s+([\w.]+)\s*;", re.M)
RANK = {"failed": 3, "error": 3, "not run": 2, "skipped": 1, "passed": 0}


def load_index(path):
    with open(path, encoding="utf-8") as f:
        return {r["id"]: r for r in csv.DictReader(line for line in f if not line.startswith("#"))}


def load_texts(path):
    texts = {}
    if path and os.path.exists(path):
        for line in open(path, encoding="utf-8"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) > 1 and IDS.fullmatch(cells[0]):
                texts[cells[0]] = cells[1]
    return texts


def strip_comments(src):
    src = re.sub(r"/\*.*?\*/", lambda m: " " * len(m.group()), src, flags=re.S)
    return re.sub(r"//[^\n]*", lambda m: " " * len(m.group()), src)


def scan_tests(root):
    """-> {(fqcn, method or None): [URS ids]} from @Requirement annotations."""
    links = {}
    for path in glob.glob(os.path.join(root, "**", "*.java"), recursive=True):
        src = strip_comments(open(path, encoding="utf-8").read())
        pkg = PACKAGE.search(src)
        top = os.path.splitext(os.path.basename(path))[0]
        fqcn = (pkg.group(1) + "." if pkg else "") + top
        for m in ANNOTATION.finditer(src):
            if "@interface" in src[max(0, m.start() - 200):m.start()]:
                continue
            decl = DECL.search(src, m.end())
            if not decl:
                continue
            ids = IDS.findall(m.group(1))
            if decl.group(1):                      # class-level (nested classes count as the top class)
                key = (fqcn if decl.group(1) == top else fqcn + "$" + decl.group(1), None)
            else:
                key = (fqcn, decl.group(2))
            links.setdefault(key, []).extend(ids)
    return links


def load_results(report_globs):
    """-> {(classname, method): status}"""
    results = {}
    for pattern in report_globs:
        for path in glob.glob(pattern, recursive=True):
            try:
                root = ET.parse(path).getroot()
            except ET.ParseError:
                continue
            for tc in root.iter("testcase"):
                cls = tc.get("classname", "")
                name = re.split(r"[(\[]", tc.get("name", ""))[0].strip()
                if tc.find("failure") is not None:
                    status = "failed"
                elif tc.find("error") is not None:
                    status = "error"
                elif tc.find("skipped") is not None:
                    status = "skipped"
                else:
                    status = "passed"
                prev = results.get((cls, name))
                results[(cls, name)] = status if prev is None or RANK[status] > RANK[prev] else prev
    return results


def build(index, links, results):
    """-> matrix {urs: [(test, status)]}, unknown {urs: [where]}"""
    matrix, unknown = defaultdict(dict), defaultdict(list)
    by_class = defaultdict(dict)
    for (cls, name), status in results.items():
        by_class[cls][name] = status
    for (cls, method), ids in links.items():
        if method is None:
            tests = {f"{cls.rsplit('.', 1)[-1]}.{n}": s for n, s in by_class.get(cls, {}).items()}
            if not tests:
                tests = {cls.rsplit(".", 1)[-1] + " (all tests)": "not run"}
        else:
            tests = {f"{cls.rsplit('.', 1)[-1]}.{method}": by_class.get(cls, {}).get(method, "not run")}
        for urs in ids:
            if urs not in index or index[urs].get("status") == "withdrawn":
                unknown[urs].append(cls.rsplit(".", 1)[-1] + (f".{method}" if method else ""))
                continue
            for t, s in tests.items():
                prev = matrix[urs].get(t)
                matrix[urs][t] = s if prev is None or RANK[s] > RANK[prev] else prev
    return {k: sorted(v.items()) for k, v in matrix.items()}, unknown


def verdict(tests):
    if not tests:
        return "not covered"
    statuses = {s for _, s in tests}
    if statuses & {"failed", "error"}:
        return "FAILED"
    if "passed" in statuses:
        return "passed"
    return "not run"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--index", default="docs/validation/urs-index.csv")
    ap.add_argument("--tests", default="backend/app/src/test/java")
    ap.add_argument("--reports", nargs="+",
                    default=["backend/**/target/surefire-reports/TEST-*.xml",
                             "backend/**/target/failsafe-reports/TEST-*.xml"])
    ap.add_argument("--urs", default="docs/product/URS.md")
    ap.add_argument("--out", default="backend/target/traceability")
    ap.add_argument("--require-mvp", action="store_true")
    a = ap.parse_args()

    index = load_index(a.index)
    texts = load_texts(a.urs)
    links = scan_tests(a.tests)
    results = load_results(a.reports)
    matrix, unknown = build(index, links, results)

    active = {k: v for k, v in index.items() if v.get("status") != "withdrawn"}
    mvp = {k for k, v in active.items() if v.get("release", "").startswith("MVP")}
    rows = [(urs, active[urs], matrix.get(urs, []), verdict(matrix.get(urs, []))) for urs in active]
    failed = [r for r in rows if r[3] == "FAILED"]
    mvp_uncovered = [r for r in rows if r[0] in mvp and r[3] != "passed"]
    covered = [r for r in rows if r[3] == "passed"]
    total_tests = len(results)
    passed_tests = sum(1 for s in results.values() if s == "passed")
    run = {
        "date": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "commit": os.environ.get("GITHUB_SHA", "local")[:12],
        "run": os.environ.get("GITHUB_RUN_NUMBER", "local"),
        "ref": os.environ.get("GITHUB_REF_NAME", ""),
    }

    os.makedirs(a.out, exist_ok=True)
    summary = (f"**{len(covered)}/{len(active)}** requirements verified by a passing test "
               f"(MVP: {len(mvp) - len(mvp_uncovered)}/{len(mvp)}); "
               f"{passed_tests}/{total_tests} tests passed; {len(failed)} requirement(s) with failing tests.")
    with open(os.path.join(a.out, "traceability.md"), "w", encoding="utf-8") as f:
        f.write(f"## Traceability: URS → test → result\n\n{summary}\n\n")
        f.write(f"Commit `{run['commit']}` · run {run['run']} · {run['date']}\n\n")
        if unknown:
            f.write("**Unknown requirement IDs in tests:** "
                    + "; ".join(f"`{k}` ({', '.join(v)})" for k, v in sorted(unknown.items())) + "\n\n")
        f.write("| Requirement | Risk | Release | Result | Tests |\n|---|---|---|---|---|\n")
        for urs, meta, tests, v in rows:
            if tests:
                listed = "<br>".join(f"{t} ({s})" for t, s in tests)
                f.write(f"| {urs} | {meta.get('risk', '')} | {meta.get('release', '')} | {v} | {listed} |\n")
        f.write(f"\n{len(active) - len(matrix)} requirement(s) have no linked test yet (see the HTML report).\n")

    badge = {"passed": "ok", "FAILED": "bad", "not run": "warn", "not covered": "none"}
    trs = []
    for urs, meta, tests, v in rows:
        text = html.escape(texts.get(urs, ""))
        listed = "<br>".join(f"<code>{html.escape(t)}</code> <span class='s-{s.replace(' ', '')}'>{s}</span>"
                             for t, s in tests) or "<span class='muted'>no test linked yet</span>"
        trs.append(f"<tr><td><b>{urs}</b>{('<div class=muted>' + text + '</div>') if text else ''}</td>"
                   f"<td>{meta.get('risk', '')}</td><td>{html.escape(meta.get('release', ''))}</td>"
                   f"<td><span class='b {badge[v]}'>{v}</span></td><td>{listed}</td></tr>")
    unknown_html = ("<p class='bad-box'>Unknown requirement IDs referenced by tests: " + "; ".join(
        f"<code>{k}</code> ({html.escape(', '.join(v))})" for k, v in sorted(unknown.items())) + "</p>") if unknown else ""
    page = f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>ArrheniQ traceability matrix</title>
<style>
body{{font:14px/1.5 Inter,system-ui,'Segoe UI',sans-serif;color:#1A1B2E;margin:32px;background:#F6F7FB}}
h1{{font-size:22px;margin:0 0 4px}} .muted{{color:#5C5F7A;font-size:12px}} table{{border-collapse:collapse;width:100%;background:#fff}}
th,td{{border:1px solid #E3E5EF;padding:6px 8px;vertical-align:top;text-align:left}} th{{background:#EEF0FB;font-size:12px;text-transform:uppercase;letter-spacing:.04em}}
.b{{padding:1px 8px;border-radius:10px;font-size:12px;font-weight:600;white-space:nowrap}} .ok{{background:#D3F9E8;color:#087F5B}}
.bad{{background:#FFE3E3;color:#C92A2A}} .warn{{background:#FFF3BF;color:#8A6100}} .none{{background:#F1F3F5;color:#5C5F7A}}
.s-passed{{color:#087F5B}} .s-failed,.s-error{{color:#C92A2A;font-weight:600}} .s-skipped,.s-notrun{{color:#8A6100}}
.bad-box{{background:#FFE3E3;padding:8px 12px;border-radius:8px}} code{{font-size:12px}}
</style></head><body>
<h1>ArrheniQ: traceability matrix (URS → test → result)</h1>
<p class="muted">Commit {html.escape(run['commit'])} · {html.escape(run['ref'])} · CI run {html.escape(run['run'])} · generated {run['date']}
by scripts/ci/traceability.py from @Requirement annotations and JUnit results.</p>
<p>{html.escape(summary).replace('**', '')}</p>{unknown_html}
<table><thead><tr><th>Requirement</th><th>Risk</th><th>Release</th><th>Result</th><th>Tests (result)</th></tr></thead>
<tbody>{''.join(trs)}</tbody></table></body></html>"""
    with open(os.path.join(a.out, "traceability.html"), "w", encoding="utf-8") as f:
        f.write(page)

    print(summary.replace("**", ""))
    problems = []
    if unknown:
        problems.append("tests reference unknown requirement IDs: " + ", ".join(sorted(unknown)))
    if failed:
        problems.append("requirements with failing tests: " + ", ".join(r[0] for r in failed))
    if a.require_mvp and mvp_uncovered:
        problems.append(f"{len(mvp_uncovered)} MVP requirement(s) without a passing test")
    not_run = sorted({t for _, _, tests, _ in rows for t, st in tests if st == "not run"})
    if not_run and results:
        print(f"::warning::{len(not_run)} linked test(s) produced no result (renamed, disabled or not run): "
              + ", ".join(not_run[:10]) + (" ..." if len(not_run) > 10 else ""))
    for p in problems:
        print("::error::" + p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
